/**
 * Cookie-import module tests — covers both exports of
 * `core/shared/cookie-import.ts` (pure logic, no I/O, no browser).
 *
 * - parseCookiesTxt() — happy path, #HttpOnly_ prefix, comments, session
 *   cookies, expired-drop-before-dedupe ordering, per-line skip reasons,
 *   engine-shape gate, value-length cap, BOM/CRLF/CR handling, boolean
 *   casing, dot rewrites (incl. the IP-literal carve-out), dedupe
 * - liftSecurityAttributes() — never-lowered security attributes on
 *   dot-blind lift-key collisions, sameSite preservation + fallback,
 *   fresh keys untouched, post-lift __Secure-/__Host- prefix gate
 */

import { describe, it, expect } from "vitest";
import { parseCookiesTxt, liftSecurityAttributes, restorePastedTabs } from "../core/shared/cookie-import.js";
import type { StoredCookie } from "../core/shared/storage-state.js";

// Fixed clock so expiry assertions are exact (unix seconds).
const NOW = 1_700_000_000;
const FUTURE = NOW + 86_400;
const PAST = NOW - 86_400;

/** Build one Netscape line from its 7 fields. */
function line(
	domain: string,
	subdomains: string,
	path: string,
	secure: string,
	expires: number | string,
	name: string,
	value: string,
): string {
	return [domain, subdomains, path, secure, String(expires), name, value].join("\t");
}

const HEADER = ["# Netscape HTTP Cookie File", "# This is a generated file! Do not edit.", ""];

describe("parseCookiesTxt", () => {
	it("parses a realistic export with header comments", () => {
		const text = [...HEADER, line(".example.com", "TRUE", "/", "TRUE", FUTURE, "sessionid", "abc123"), line("example.org", "FALSE", "/login", "FALSE", FUTURE, "theme", "dark")].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([
			{ name: "sessionid", value: "abc123", domain: ".example.com", path: "/", expires: FUTURE, httpOnly: false, secure: true, sameSite: "Lax" },
			{ name: "theme", value: "dark", domain: "example.org", path: "/login", expires: FUTURE, httpOnly: false, secure: false, sameSite: "Lax" },
		]);
		expect(result.skipped).toEqual([]);
		expect(result.expired).toBe(0);
		expect(result.duplicates).toBe(0);
	});

	it("parses #HttpOnly_ lines with the marker stripped", () => {
		const text = line("#HttpOnly_.example.com", "TRUE", "/", "TRUE", FUTURE, "sid", "v");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toHaveLength(1);
		expect(result.cookies[0]?.httpOnly).toBe(true);
		expect(result.cookies[0]?.domain).toBe(".example.com");
	});

	it("maps expires 0 and -1 to the session sentinel -1", () => {
		const text = [
			line("example.com", "FALSE", "/", "FALSE", 0, "a", "1"),
			line("example.com", "FALSE", "/", "FALSE", -1, "b", "2"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies.map((c) => c.expires)).toEqual([-1, -1]);
	});

	it("drops already-expired cookies and counts them", () => {
		const text = line("example.com", "FALSE", "/", "FALSE", PAST, "a", "1");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([]);
		expect(result.expired).toBe(1);
	});

	it("survives a far-future expires when nowSec is omitted (seconds default)", () => {
		const text = line("example.com", "FALSE", "/", "FALSE", Math.floor(Date.now() / 1000) + 86_400, "a", "1");
		const result = parseCookiesTxt(text);
		expect(result.cookies).toHaveLength(1);
		expect(result.expired).toBe(0);
	});

	it("skips malformed lines with exact line numbers and reason codes", () => {
		const text = [
			...HEADER, // lines 1-3
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "ok", "1"), // 4
			"too\tfew\tfields\there", // 5
			"", // 6 — blank, not counted
			line("example.com", "MAYBE", "/", "FALSE", FUTURE, "a", "1"), // 7 — bool
			line("example.com", "FALSE", "/", "FALSE", "abc", "a", "1"), // 8 — expiry
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "", "1"), // 9 — empty-key
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([expect.objectContaining({ name: "ok" })]);
		expect(result.skipped).toEqual([
			{ line: 5, reason: "field-count" },
			{ line: 7, reason: "bool" },
			{ line: 8, reason: "expiry" },
			{ line: 9, reason: "empty-key" },
		]);
	});

	it("treats comment lines and blank/whitespace-only lines as non-data", () => {
		const text = [
			"# comment",
			"# Generated by SomeExtension 2.1",
			"",
			"   ",
			"\t\t\t", // tab-only padding
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "a", "1"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toHaveLength(1);
		expect(result.skipped).toEqual([]);
	});

	it("skips engine-shape violations", () => {
		const text = [
			// ms-epoch magnitude
			line("example.com", "FALSE", "/", "FALSE", 1_700_000_000_000, "a", "1"),
			// beyond Chromium's max accepted expires
			line("example.com", "FALSE", "/", "FALSE", 253_402_300_800, "b", "1"),
			// domain over 253 bytes
			line(`a${".abcdefghij".repeat(25)}`, "FALSE", "/", "FALSE", FUTURE, "c", "1"),
			// non-hostname characters
			line("exa mple.com", "FALSE", "/", "FALSE", FUTURE, "d", "1"),
			// control char in name / in value
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "na\u0001me", "1"),
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "e", "va\u007flue"),
			// whitespace-only name
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "   ", "1"),
			// __Host- with a non-/ path, with a dotted domain, and with
			// includeSubdomains=TRUE (the rewrite would add the dot)
			line("example.com", "FALSE", "/x", "TRUE", FUTURE, "__Host-a", "1"),
			line(".example.com", "FALSE", "/", "TRUE", FUTURE, "__Host-b", "1"),
			line("example.com", "TRUE", "/", "TRUE", FUTURE, "__Host-c", "1"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([]);
		expect(result.skipped).toHaveLength(10);
		expect(result.skipped.every((s) => s.reason === "engine-shape")).toBe(true);
	});

	it("accepts a __Host- cookie with a / path and dotless domain", () => {
		const text = line("example.com", "FALSE", "/", "TRUE", FUTURE, "__Host-a", "1");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toHaveLength(1);
	});

	// An empty path field stores as "/" (pathRaw || "/"), so it must pass the
	// same __Host- gate the explicit "/" line passes.
	it("accepts a __Host- cookie with an empty path field (stored as /)", () => {
		const text = line("example.com", "FALSE", "", "TRUE", FUTURE, "__Host-a", "1");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toHaveLength(1);
		expect(result.cookies[0]?.path).toBe("/");
	});

	it("skips name+value pairs over 4096 bytes, measuring bytes not UTF-16 units", () => {
		// 2048 é chars = 4096 UTF-8 bytes; UTF-16 length is only 2048.
		const overCap = line("example.com", "FALSE", "/", "FALSE", FUTURE, "c", "é".repeat(2048));
		// Exactly 4096 bytes is accepted (the cap is exclusive; pinned by the
		// chromium contract case at addCookies).
		const atCap = line("example.com", "FALSE", "/", "FALSE", FUTURE, "c", "x".repeat(4095));
		const result = parseCookiesTxt([overCap, atCap].join("\n"), NOW);
		expect(result.skipped).toEqual([{ line: 1, reason: "value-length" }]);
		expect(result.cookies).toHaveLength(1);
	});

	it("skips malformed expires values", () => {
		const text = [
			line("example.com", "FALSE", "/", "FALSE", "abc", "a", "1"),
			line("example.com", "FALSE", "/", "FALSE", -5, "b", "1"),
			line("example.com", "FALSE", "/", "FALSE", "9999999999junk", "c", "1"),
			line("example.com", "FALSE", "/", "FALSE", "99999999999999999999", "d", "1"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([]);
		expect(result.skipped).toHaveLength(4);
		expect(result.skipped.every((s) => s.reason === "expiry")).toBe(true);
	});

	it("accepts lowercase true/false booleans but skips garbage", () => {
		const text = [
			line("example.com", "true", "/", "false", FUTURE, "a", "1"),
			line("example.com", "FALSE", "/", "TRUE", FUTURE, "b", "1"),
			line("example.com", "maybe", "/", "FALSE", FUTURE, "c", "1"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies.map((c) => c.name)).toEqual(["a", "b"]);
		expect(result.skipped).toEqual([{ line: 3, reason: "bool" }]);
	});

	it("handles CRLF, bare-CR, and a UTF-8 BOM prefix", () => {
		const body = [line("example.com", "FALSE", "/", "FALSE", FUTURE, "a", "1"), line("example.com", "FALSE", "/", "FALSE", FUTURE, "b", "2")];
		for (const sep of ["\r\n", "\r", "\n"]) {
			const result = parseCookiesTxt(`\uFEFF${HEADER.join(sep)}${sep}${body.join(sep)}`, NOW);
			expect(result.cookies.map((c) => c.name)).toEqual(["a", "b"]);
			expect(result.skipped).toEqual([]);
		}
	});

	it("does not trim cookie lines (an empty value keeps its trailing TAB)", () => {
		const text = line("example.com", "FALSE", "/", "FALSE", FUTURE, "a", "");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies[0]?.value).toBe("");
	});

	it("applies the dot rewrites from includeSubdomains, except for IP literals", () => {
		const text = [
			line("example.com", "TRUE", "/", "FALSE", FUTURE, "a", "1"), // dotless TRUE gains a dot
			line(".example.com", "FALSE", "/", "FALSE", FUTURE, "b", "1"), // dotted FALSE loses the dot
			line("127.0.0.1", "TRUE", "/", "FALSE", FUTURE, "c", "1"), // IP: no rewrite either way
			line("127.0.0.1", "FALSE", "/", "FALSE", FUTURE, "d", "1"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies.map((c) => c.domain)).toEqual([
			".example.com",
			"example.com",
			"127.0.0.1",
			"127.0.0.1",
		]);
	});

	it("lowercases the parsed domain", () => {
		const result = parseCookiesTxt(line("Example.COM", "FALSE", "/", "FALSE", FUTURE, "a", "1"), NOW);
		expect(result.cookies[0]?.domain).toBe("example.com");
	});

	it("dedupes exact keys last-wins and counts duplicates", () => {
		const text = [
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "sid", "first"),
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "sid", "second"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([expect.objectContaining({ name: "sid", value: "second" })]);
		expect(result.duplicates).toBe(1);
	});

	it("collapses case-differing domains to one cookie but keeps dot variants as two", () => {
		const text = [
			line("Example.COM", "FALSE", "/", "FALSE", FUTURE, "sid", "a"),
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "sid", "b"),
			line(".example.com", "TRUE", "/", "FALSE", FUTURE, "sid", "c"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies.map((c) => c.domain).sort()).toEqual([".example.com", "example.com"]);
		expect(result.cookies.find((c) => c.domain === "example.com")?.value).toBe("b");
		expect(result.duplicates).toBe(1);
	});

	it("runs expired-drop before dedupe so a valid earlier line survives", () => {
		const text = [
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "sid", "good"),
			line("example.com", "FALSE", "/", "FALSE", PAST, "sid", "expired-dup"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies).toEqual([expect.objectContaining({ value: "good" })]);
		expect(result.expired).toBe(1);
		expect(result.duplicates).toBe(0);
	});

	it("returns parsed cookies and skips together for a mixed file", () => {
		const text = [
			...HEADER,
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "good", "1"),
			"garbage line without tabs",
			line("example.com", "FALSE", "/", "FALSE", FUTURE, "also-good", "2"),
		].join("\n");
		const result = parseCookiesTxt(text, NOW);
		expect(result.cookies.map((c) => c.name)).toEqual(["good", "also-good"]);
		expect(result.skipped).toEqual([{ line: 5, reason: "field-count" }]);
	});
});

describe("restorePastedTabs", () => {
	// A pasted line whose tabs the editor expanded to 4 spaces: the 6
	// separator runs between the 7 fields. Values carrying short space runs
	// are appended verbatim in the value field.
	const pasted = (value: string): string =>
		`example.com    FALSE    /    FALSE    ${FUTURE}    sid    ${value}`;

	it("refuses runs of 5+ whose length is not a multiple of 4 (ambiguous with an expanded tab)", () => {
		for (const run of [5, 6, 7, 9]) {
			const text = pasted("a" + " ".repeat(run) + "b");
			expect(restorePastedTabs(text)).toEqual({ ok: false });
		}
	});

	it("round-trips 1-3 space runs inside a value unchanged (guard's false-positive boundary)", () => {
		for (const run of [1, 2, 3]) {
			const result = restorePastedTabs(pasted("a" + " ".repeat(run) + "b"));
			// Separators become tabs; the value's short runs survive intact.
			expect(result).toEqual({ ok: true, text: `example.com\tFALSE\t/\tFALSE\t${FUTURE}\tsid\ta${" ".repeat(run)}b` });
		}
	});

	it("restores runs of 4, 8 and 12 spaces to one, two and three tabs", () => {
		for (const [run, tabs] of [[4, 1], [8, 2], [12, 3]] as const) {
			const result = restorePastedTabs(pasted("a" + " ".repeat(run) + "b"));
			expect(result).toEqual({ ok: true, text: `example.com\tFALSE\t/\tFALSE\t${FUTURE}\tsid\ta${"\t".repeat(tabs)}b` });
		}
	});

	it("returns real-tab text unchanged — no guard, no replace — even with 4-space and 5+ runs", () => {
		const text = line("example.com", "FALSE", "/", "FALSE", FUTURE, "sid", "a    b     c");
		expect(restorePastedTabs(text)).toEqual({ ok: true, text });
	});
});

describe("liftSecurityAttributes", () => {
	const base = (overrides: Partial<StoredCookie> = {}): StoredCookie => ({
		name: "sid",
		value: "v",
		domain: "example.com",
		path: "/",
		expires: FUTURE,
		httpOnly: false,
		secure: false,
		sameSite: "Lax",
		...overrides,
	});

	it("lifts httpOnly/secure from the existing cookie on collision, values stay file-wins", () => {
		const existing = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: true, secure: true, sameSite: "None" as const },
		];
		const incoming = [base({ value: "new", expires: FUTURE, httpOnly: false, secure: false, sameSite: "Lax" })];
		const result = liftSecurityAttributes(existing, incoming);
		expect(result.collidedKeys).toHaveLength(1);
		expect(result.rejectedKeys).toHaveLength(0);
		expect(result.cookies).toEqual([
			expect.objectContaining({ value: "new", expires: FUTURE, httpOnly: true, secure: true, sameSite: "None" }),
		]);
	});

	it("matches across case-differing domains", () => {
		const existing = [
			{ name: "sid", value: "old", domain: "Example.com", path: "/", expires: PAST, httpOnly: true, secure: false, sameSite: "Lax" as const },
		];
		const result = liftSecurityAttributes(existing, [base()]);
		expect(result.collidedKeys).toHaveLength(1);
		expect(result.cookies[0]?.httpOnly).toBe(true);
	});

	it("lifts upward-only in both directions (incoming true stays true)", () => {
		const existing = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: false, secure: false, sameSite: "Lax" as const },
		];
		const result = liftSecurityAttributes(existing, [base({ httpOnly: true, secure: true })]);
		expect(result.cookies[0]?.httpOnly).toBe(true);
		expect(result.cookies[0]?.secure).toBe(true);
	});

	it("keeps the existing sameSite and falls back to the parsed value when absent", () => {
		const withSameSite = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: false, secure: false, sameSite: "Strict" as const },
		];
		const withoutSameSite = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: false, secure: false },
		];
		const liftedKept = liftSecurityAttributes(withSameSite, [base({ sameSite: "Lax" })]);
		expect(liftedKept.cookies[0]?.sameSite).toBe("Strict");
		const liftedFallback = liftSecurityAttributes(withoutSameSite, [base({ sameSite: "Lax" })]);
		expect(liftedFallback.cookies[0]?.sameSite).toBe("Lax");
	});

	it("passes fresh keys through unchanged", () => {
		const existing = [
			{ name: "other", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: true, secure: true, sameSite: "None" as const },
		];
		const incoming = [base({ httpOnly: false, secure: false, sameSite: "Lax" })];
		const result = liftSecurityAttributes(existing, incoming);
		expect(result.collidedKeys).toHaveLength(0);
		expect(result.cookies).toEqual(incoming);
	});

	it("keeps dot-variant identity but lifts across the dot", () => {
		const existing = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: true, secure: true, sameSite: "Strict" as const },
			{ name: "sid", value: "old2", domain: ".example.com", path: "/", expires: PAST, httpOnly: false, secure: false, sameSite: "Lax" as const },
		];
		const incoming = [base({ domain: "example.com" }), base({ domain: ".example.com" })];
		const result = liftSecurityAttributes(existing, incoming);
		expect(result.cookies).toHaveLength(2);
		expect(result.collidedKeys).toHaveLength(2);
		// Both incoming cookies lifted from the dot-blind match set.
		for (const c of result.cookies) {
			expect(c.httpOnly).toBe(true);
			expect(c.secure).toBe(true);
			expect(c.sameSite).toBe("Strict");
		}
	});

	it("ORs booleans and takes sameSite from the first match carrying the field", () => {
		const existing = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: true, secure: false },
			{ name: "sid", value: "old2", domain: ".example.com", path: "/", expires: PAST, httpOnly: false, secure: true, sameSite: "Strict" as const },
		];
		const result = liftSecurityAttributes(existing, [base({ sameSite: "Lax" })]);
		expect(result.cookies[0]?.httpOnly).toBe(true);
		expect(result.cookies[0]?.secure).toBe(true);
		expect(result.cookies[0]?.sameSite).toBe("Strict");

		// Order pin: the first match carrying the field wins.
		const ordered = [
			{ name: "sid", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: false, secure: false, sameSite: "Lax" as const },
			{ name: "sid", value: "old2", domain: ".example.com", path: "/", expires: PAST, httpOnly: false, secure: false, sameSite: "Strict" as const },
		];
		const result2 = liftSecurityAttributes(ordered, [base()]);
		expect(result2.cookies[0]?.sameSite).toBe("Lax");
	});

	it("rejects a still-insecure __Secure-/__Host- cookie after the lift", () => {
		const fresh = liftSecurityAttributes([], [base({ name: "__Host-a", secure: false })]);
		expect(fresh.cookies).toEqual([]);
		expect(fresh.rejectedKeys).toHaveLength(1);

		const freshSecurePrefix = liftSecurityAttributes([], [base({ name: "__Secure-x", secure: false })]);
		expect(freshSecurePrefix.rejectedKeys).toHaveLength(1);

		// Repair case: the existing state holds the __Host- cookie secure, so
		// the marker-less import is lifted to secure:true and survives.
		const existing = [
			{ name: "__Host-a", value: "old", domain: "example.com", path: "/", expires: PAST, httpOnly: false, secure: true, sameSite: "Lax" as const },
		];
		const repaired = liftSecurityAttributes(existing, [base({ name: "__Host-a", secure: false })]);
		expect(repaired.rejectedKeys).toHaveLength(0);
		expect(repaired.collidedKeys).toHaveLength(1);
		expect(repaired.cookies[0]?.secure).toBe(true);
	});
});
